"""Run the full evaluation suite and write reports/eval-suite.json and EVAL_REPORT.md.

Sections that need a credential or Docker report `skipped` with the reason; they are
never filled with invented numbers.

    .venv-eval/bin/python evals/run_all.py            # from the repository root
    .venv-eval/bin/python scripts/with_env.py .venv-eval/bin/python evals/run_all.py
"""
import json
import os
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from evals import calibration, collect, deterministic, judge

ROOT = Path(__file__).resolve().parents[1]
APP_PYTHON = ROOT / '.venv/bin/python'


def section(fn):
    try:
        return fn()
    except judge.JudgeUnavailable as exc:
        return {'status': 'skipped', 'reason': str(exc)}
    except Exception as exc:
        return {'status': 'error', 'reason': f'{type(exc).__name__}: {str(exc)[:300]}'}


def unit_tests():
    python = str(APP_PYTHON if APP_PYTHON.exists() else sys.executable)
    out = subprocess.run([python, '-m', 'pytest', '-q', 'tests', 'evals/tests'], cwd=ROOT, capture_output=True, text=True, timeout=600)
    tail = out.stdout.strip().splitlines()[-1] if out.stdout.strip() else out.stderr[-200:]
    m = {k: int(v) for v, k in re.findall(r'(\d+) (passed|failed|error)', tail)}
    return {'status': 'passed' if out.returncode == 0 else 'failed', **m, 'summary': tail}


def det():
    r = deterministic.evaluate_system()
    return {'status': 'passed' if r['passed'] else 'failed', **r}


def judge_calibration():
    if not judge.api_key():
        raise judge.JudgeUnavailable('GEMINI_API_KEY (or JUDGE_API_KEY) is not set')
    results = judge.judge_many(calibration.CALIBRATION)
    agree = calibration.agreement(results)
    return {'status': 'passed' if agree['agreement'] >= 0.85 else 'failed', 'judge_model': judge.judge_model(), **agree,
            'scores': {r['id']: {d: r['scores'][d]['score'] for d in judge.DIMENSIONS} for r in results}}


def live_records():
    return collect.collect()


def judge_live():
    records = live_records()
    if not records:
        return {'status': 'skipped', 'reason': 'No runtime/*/state.json: live repair runs need Docker + a model key (python scripts/evaluate.py)'}
    results = judge.judge_many(records)
    mean = {d: sum(r['scores'][d]['score'] for r in results) / len(results) for d in judge.DIMENSIONS}
    return {'status': 'passed' if all(r['verdict'] == 'pass' for r in results) else 'failed', 'judge_model': judge.judge_model(), 'records': len(results), 'mean_scores': mean,
            'results': results}


def ragas_live():
    from evals import ragas_run
    records = live_records()
    if not records:
        return {'status': 'skipped', 'reason': 'No runtime/*/state.json to evaluate'}
    if not judge.api_key():
        raise judge.JudgeUnavailable('GEMINI_API_KEY (or JUDGE_API_KEY) is not set')
    result = ragas_run.run(records)
    return {'status': 'passed' if (result['metrics'].get('faithfulness') or 0) >= 0.8 else 'failed', **result}


def render(report):
    lines = ['# Evaluation report', '', f"Generated by `evals/run_all.py`. Overall: **{report['overall']}**", '', '| Section | Status | Detail |', '| --- | --- | --- |']
    for name, s in report['sections'].items():
        detail = s.get('reason') or s.get('summary') if isinstance(s.get('summary'), str) else s.get('reason', '')
        if name == 'deterministic':
            sm = s['summary']
            detail = f"{sm['cases_passed_all_checks']}/{sm['cases']} cases, {sm['system_checks_passed']}/{sm['system_checks']} system checks"
        if name == 'judge_calibration' and s.get('agreement') is not None:
            detail = f"agreement {s['agreement']:.0%} on {s['items']} synthetic items"
        lines.append(f"| {name} | {s['status']} | {detail or ''} |")
    d = report['sections']['deterministic']
    if 'cases' in d:
        sm = d['summary']
        lines += ['', '## Outcome and process (deterministic)', '',
                  f"- Repair success (reached human gate with verified tests): {sm['repair_success_rate']:.0%}",
                  f"- First-attempt success: {sm['first_attempt_success_rate']:.0%}; mean attempts {sm['mean_attempts']:.2f}",
                  f"- Tokens: {sm['total_input_tokens']} in / {sm['total_output_tokens']} out", '',
                  '| Case | Attempts | Invalid outputs | Checks passed |', '| --- | --- | --- | --- |']
        for c in d['cases']:
            lines.append(f"| {c['case_id']} | {c['attempts']} | {c['usage']['invalid_outputs']} | {sum(x['passed'] for x in c['checks'])}/{len(c['checks'])} |")
        lines += ['', f"Caveat: {d['caveat']}", '', 'Known limits: ' + '; '.join(f"{k['item']} — {k['status']} ({k['observed']})" for k in d['known_limits'])]
    return '\n'.join(lines) + '\n'


def main():
    sections = {'unit_tests': section(unit_tests), 'deterministic': section(det), 'judge_calibration': section(judge_calibration),
                'judge_live_repairs': section(judge_live), 'ragas_live_repairs': section(ragas_live)}
    bad = [n for n, s in sections.items() if s['status'] in ('failed', 'error')]
    skipped = [n for n, s in sections.items() if s['status'] == 'skipped']
    report = {'overall': 'FAILED' if bad else ('INCOMPLETE' if skipped else 'PASSED'), 'failed': bad, 'skipped': skipped, 'judge_model': judge.judge_model(), 'sections': sections}
    (ROOT / 'reports/eval-suite.json').write_text(json.dumps(report, indent=2) + '\n')
    (ROOT / 'EVAL_REPORT.md').write_text(render(report))
    print(render(report))
    return 1 if bad else 0


if __name__ == '__main__':
    raise SystemExit(main())
